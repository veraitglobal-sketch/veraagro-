export function translateEnToBg(text) {
  for (const [re, repl] of PHRASE_RULES) {
    if (re.test(text)) return text.replace(re, repl);
  }
  return text.replace(/\b[A-Za-z][A-Za-z'-]*\b/g, (word) => {
    const lower = word.toLowerCase();
    if (WORDS[lower]) {
      const bg = WORDS[lower];
      if (word === word.toUpperCase()) return bg.toUpperCase();
      if (word[0] === word[0].toUpperCase()) return bg.charAt(0).toUpperCase() + bg.slice(1);
      return bg;
    }
    return word;
  });
}
