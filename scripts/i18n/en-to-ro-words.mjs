export function translateEnToRo(text) {
  for (const [re, repl] of PHRASE_RULES) {
    if (re.test(text)) return text.replace(re, repl);
  }
  return text.replace(/\b[A-Za-z][A-Za-z'-]*\b/g, (word) => {
    const lower = word.toLowerCase();
    if (WORDS[lower]) {
      const ro = WORDS[lower];
      if (word === word.toUpperCase()) return ro.toUpperCase();
      if (word[0] === word[0].toUpperCase()) return ro.charAt(0).toUpperCase() + ro.slice(1);
      return ro;
    }
    return word;
  });
}
