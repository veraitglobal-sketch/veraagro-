export function translateEnToFr(text) {
  for (const [re, repl] of PHRASE_RULES) {
    if (re.test(text)) return text.replace(re, repl);
  }
  return text.replace(/\b[A-Za-z][A-Za-z'-]*\b/g, (word) => {
    const lower = word.toLowerCase();
    if (WORDS[lower]) {
      const fr = WORDS[lower];
      if (word === word.toUpperCase()) return fr.toUpperCase();
      if (word[0] === word[0].toUpperCase()) return fr.charAt(0).toUpperCase() + fr.slice(1);
      return fr;
    }
    return word;
  });
}
