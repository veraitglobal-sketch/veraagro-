export function translateEnToEs(text) {
  for (const [re, repl] of PHRASE_RULES) {
    if (re.test(text)) return text.replace(re, repl);
  }
  return text.replace(/\b[A-Za-z][A-Za-z'-]*\b/g, (word) => {
    const lower = word.toLowerCase();
    if (WORDS[lower]) {
      const es = WORDS[lower];
      if (word === word.toUpperCase()) return es.toUpperCase();
      if (word[0] === word[0].toUpperCase()) return es.charAt(0).toUpperCase() + es.slice(1);
      return es;
    }
    return word;
  });
}
